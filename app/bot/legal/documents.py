def _sections(kind: LegalDocKind, settings: Settings) -> list[str]:
    if kind is LegalDocKind.PRIVACY:
        return _privacy_sections(settings)
    return _terms_sections(settings)


def _pack_pages(sections: list[str]) -> list[str]:
    pages: list[str] = []
    current = ""
    for block in sections:
        candidate = f"{current}\n\n{block}".strip() if current else block
        if len(candidate) <= _MAX_PAGE_CHARS:
            current = candidate
            continue
        if current:
            pages.append(current)
        if len(block) <= _MAX_PAGE_CHARS:
            current = block
        else:
            # редкий случай: режем по абзацам
            start = 0
            while start < len(block):
                chunk = block[start : start + _MAX_PAGE_CHARS]
                pages.append(chunk)
                start += _MAX_PAGE_CHARS
            current = ""
    if current:
        pages.append(current)
    return pages or [""]


def page_count(kind: LegalDocKind, settings: Settings) -> int:
    return len(_pack_pages(_sections(kind, settings)))


def document_page(kind: LegalDocKind, page_index: int, settings: Settings) -> str | None:
    pages = _pack_pages(_sections(kind, settings))
    if page_index < 0 or page_index >= len(pages):
        return None
    total = len(pages)
    header = f"<i>Стр. {page_index + 1} из {total}</i>\n\n" if total > 1 else ""
    return header + pages[page_index]
