"""Примеры push-сообщений при переключении уведомлений."""


def preview_new_reviews(*, negative_only: bool) -> str:
    if negative_only:
        return (
            "📬 <i>Пример</i>\n"
            "🟣 Магазин · ⭐⭐ (2/5)\n"
            "«Размер не подошёл…»\n"
            "<b>Только негатив</b> — так придёт при включённом фильтре."
        )
    return (
        "📬 <i>Пример</i>\n"
        "🟣 Магазин · ⭐⭐⭐⭐⭐ (5/5)\n"
        "«Отличный товар!»\n"
        "Новые отзывы в очереди после sync."
    )


def preview_daily_digest() -> str:
    return (
        "📊 <i>Пример дайджеста</i>\n"
        "За вчера: генерации <b>12</b> · publish <b>4</b> · в очереди <b>3</b>."
    )


def preview_stale_reviews() -> str:
    return (
        "⏰ <i>Пример напоминания</i>\n"
        "В очереди <b>5</b> отзывов без ответа более 24 ч."
    )


def preview_buyer_questions() -> str:
    return (
        "❓ <i>Пример</i>\n"
        "🟣 Магазин: +<b>2</b> вопроса (всего без ответа: <b>5</b>)."
    )
